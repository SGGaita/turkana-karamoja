/**
 * Runs before `next build` (npm "prebuild", after fetch-site-header.js). Saves Karamoja → Site settings → Installed
 * app (`karamoja/v1/pwa`) into lib/pwa.snapshot.json and downloads its icons into public/icons/cms/<version>/, so the
 * service worker precaches them and the manifest, the page head and push notifications use files on this site (FE-08).
 *
 * Never fails the build: if the CMS is unreachable or a download fails, the previous snapshot and icons are kept;
 * a snapshot whose icon files are missing falls back to the built-in icons in public/icons/.
 */
const fs = require('fs');
const path = require('path');
const { loadEnvConfig } = require('@next/env');

loadEnvConfig(process.cwd());

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'lib', 'pwa.snapshot.json');
const ICON_ROOT = path.join(ROOT, 'public', 'icons', 'cms');
const TIMEOUT_MS = 45000;
const MAX_ICON_BYTES = 2 * 1024 * 1024;

const note = 'Auto-generated by scripts/fetch-pwa.js before each build. Do not edit by hand.';

function readSnapshot() {
  try {
    return JSON.parse(fs.readFileSync(OUT, 'utf8'));
  } catch {
    return { _note: note, fetchedAt: null, pwa: null, local: null };
  }
}

function writeSnapshot(snapshot) {
  fs.writeFileSync(OUT, `${JSON.stringify({ _note: note, ...snapshot }, null, 2)}\n`);
}

/** Every site path a snapshot's icon set points at. */
function localPaths(files) {
  if (!files) return [];
  return [
    ...(files.manifest || []).map((i) => i.src),
    files.apple_touch_icon,
    ...(files.favicon || []),
    files.badge,
  ].filter(Boolean);
}

/** True when every icon file of the snapshot is on disk. */
function localComplete(local) {
  const list = localPaths(local?.files);
  return list.length > 0 && list.every((p) => fs.existsSync(path.join(ROOT, 'public', p)));
}

async function get(url, as) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), TIMEOUT_MS);
  try {
    const res = await fetch(url, { signal: controller.signal });
    if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
    if (as === 'json') return await res.json();
    const buf = Buffer.from(await res.arrayBuffer());
    if (buf.length > MAX_ICON_BYTES) throw new Error(`${url} is larger than 2 MB`);
    if (buf.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a') throw new Error(`${url} is not a PNG`);
    return buf;
  } finally {
    clearTimeout(timer);
  }
}

/** Downloads one icon set into public/icons/cms/<version>/ and returns the same set with site paths. */
async function download(pwa) {
  const version = String(pwa.icons_version || '');
  if (!/^[a-f0-9]{6,40}$/.test(version)) throw new Error('unexpected icons_version');
  const dir = path.join(ICON_ROOT, version);
  const tmp = `${dir}.tmp`;
  fs.rmSync(tmp, { recursive: true, force: true });
  fs.mkdirSync(tmp, { recursive: true });
  const seen = new Map();
  const local = async (url) => {
    if (!url) return null;
    if (seen.has(url)) return seen.get(url);
    const name = path.basename(new URL(url).pathname);
    if (!/^[a-z0-9-]+\.png$/.test(name)) throw new Error(`unexpected icon name ${name}`);
    fs.writeFileSync(path.join(tmp, name), await get(url, 'buffer'));
    const p = `/icons/cms/${version}/${name}`;
    seen.set(url, p);
    return p;
  };
  const icons = pwa.icons;
  const files = {
    manifest: [],
    apple_touch_icon: await local(icons.apple_touch_icon),
    favicon: [],
    badge: await local(icons.badge),
  };
  for (const i of icons.manifest || []) {
    files.manifest.push({ ...i, src: await local(i.src) });
  }
  for (const f of icons.favicon || []) {
    files.favicon.push(await local(f));
  }
  fs.rmSync(dir, { recursive: true, force: true });
  fs.renameSync(tmp, dir);
  // Older versions are no longer referenced.
  for (const old of fs.readdirSync(ICON_ROOT)) {
    if (old !== version) fs.rmSync(path.join(ICON_ROOT, old), { recursive: true, force: true });
  }
  return { version, files };
}

(async () => {
  const previous = readSnapshot();
  const base = (process.env.NEXT_PUBLIC_WP_BASE_URL || '').replace(/\/$/, '');
  const keepPrevious = (why) => {
    if (previous.local && !localComplete(previous.local)) {
      writeSnapshot({ ...previous, local: null });
      console.warn(`[pwa] ${why} — icon files of the last snapshot are missing; using the built-in icons.`);
    } else {
      console.warn(`[pwa] ${why} — keeping the existing snapshot.`);
    }
  };
  if (!base || base.includes('your-wordpress-site')) {
    keepPrevious('NEXT_PUBLIC_WP_BASE_URL not set');
    return;
  }
  let pwa;
  try {
    pwa = await get(`${base}/wp-json/karamoja/v1/pwa?lang=en`, 'json');
    if (!pwa || typeof pwa !== 'object' || !('short_name' in pwa)) throw new Error('not a Karamoja Core answer');
  } catch (err) {
    keepPrevious(`Could not read the app settings from the CMS (${err.message})`);
    return;
  }
  let local = null;
  if (!pwa.icons_version) {
    fs.rmSync(ICON_ROOT, { recursive: true, force: true }); // No app icon in the CMS: the built-in icons.
  } else if (pwa.icons) {
    if (previous.local?.version === pwa.icons_version && localComplete(previous.local)) {
      local = previous.local;
    } else {
      try {
        fs.mkdirSync(ICON_ROOT, { recursive: true });
        local = await download(pwa);
      } catch (err) {
        console.warn(`[pwa] Could not download the app icons (${err.message}) — the manifest uses the CMS addresses.`);
        local = previous.local && localComplete(previous.local) ? previous.local : null;
      }
    }
  }
  writeSnapshot({ fetchedAt: new Date().toISOString(), pwa, local });
  console.log(`[pwa] App settings saved from ${base}${local ? ` (icons ${local.version})` : ' (built-in icons)'}.`);
})();
