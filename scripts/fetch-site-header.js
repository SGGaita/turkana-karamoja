/**
 * Runs before `next build` (npm "prebuild"). Saves the CMS site header (logo, menu,
 * top bar) for every locale into lib/site-header.snapshot.json so every page's
 * HTML ships with the real CMS menu — no waiting on the slow CMS in the browser.
 *
 * Never fails the build: if the CMS is unreachable, the previous snapshot is kept.
 */
const fs = require('fs');
const path = require('path');
const { loadEnvConfig } = require('@next/env');

loadEnvConfig(process.cwd());

const LOCALES = ['en', 'sw', 'tu', 'pk', 'ng'];
const OUT = path.join(__dirname, '..', 'lib', 'site-header.snapshot.json');
const TIMEOUT_MS = 45000;

async function fetchLocale(base, locale) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), TIMEOUT_MS);
  try {
    const res = await fetch(`${base}/wp-json/tk/v1/site-header?lang=${locale}`, { signal: controller.signal });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const raw = await res.json();
    if (!raw || !Array.isArray(raw.nav_links)) throw new Error('unexpected response shape');
    const { translations, ...rest } = raw; // translations are already applied per locale
    return rest;
  } finally {
    clearTimeout(timer);
  }
}

const CMS_LOCALES = ['en', 'sw', 'pk', 'tk'];

/** Karamoja → Site settings, if Karamoja Core is installed and the settings have been saved. */
async function fetchGlobals(base) {
  const out = {};
  for (const locale of CMS_LOCALES) {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), TIMEOUT_MS);
    try {
      // eslint-disable-next-line no-await-in-loop
      const res = await fetch(`${base}/wp-json/karamoja/v1/globals?lang=${locale}`, { signal: controller.signal });
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      // eslint-disable-next-line no-await-in-loop
      const g = await res.json();
      if (!g || !g.sections || !g.updated_at) return null; // Not saved yet: the website keeps the old header/footer.
      out[locale] = g;
    } finally {
      clearTimeout(timer);
    }
  }
  return out;
}

(async () => {
  const base = (process.env.NEXT_PUBLIC_WP_BASE_URL || '').replace(/\/$/, '');
  if (!base || base.includes('your-wordpress-site')) {
    console.log('[site-header] NEXT_PUBLIC_WP_BASE_URL not set — keeping existing snapshot.');
    return;
  }
  try {
    const results = await Promise.all(LOCALES.map((l) => fetchLocale(base, l)));
    const locales = Object.fromEntries(LOCALES.map((l, i) => [l, results[i]]));
    let globals = null;
    try {
      globals = await fetchGlobals(base);
    } catch (err) {
      console.warn(`[site-header] Site settings not available (${err.message}).`);
    }
    const snapshot = {
      _note: 'Auto-generated by scripts/fetch-site-header.js before each build. Do not edit by hand.',
      fetchedAt: new Date().toISOString(),
      locales,
      ...(globals ? { globals } : {}),
    };
    fs.writeFileSync(OUT, `${JSON.stringify(snapshot, null, 2)}\n`);
    console.log(`[site-header] Snapshot updated from ${base} (${LOCALES.join(', ')})${globals ? ' with site settings' : ''}.`);
  } catch (err) {
    console.warn(`[site-header] Could not refresh from CMS (${err.message}) — keeping existing snapshot.`);
  }
})();
